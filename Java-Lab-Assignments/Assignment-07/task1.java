// Task 1: Count iterations of one loop

public class task1 {
    public static void main(String[] args) {

        int n = 5;
        int count = 0;

        for (int i = 1; i <= n; i++) {
            count++;
        }

        System.out.println("Number of iterations: " + count);
        System.out.println("Time Complexity: O(n)");
    }
}

